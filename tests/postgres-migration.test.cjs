require('./postgres-guard.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { scryptSync } = require('node:crypto');
const { DatabaseSync } = require('node:sqlite');
const { importSqlite } = require('../scripts/import-sqlite.cjs');
const { connect, schemaName } = require('../scripts/postgres-tools.cjs');

(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vp-pg-migration-'));
  const source = path.join(directory, 'fixture.sqlite');
  const sqlite = new DatabaseSync(source);
  sqlite.exec('PRAGMA journal_mode=WAL; PRAGMA wal_autocheckpoint=0; PRAGMA foreign_keys=ON;');
  const schema = fs
    .readFileSync('migrations/001_initial.sql', 'utf8')
    .replace(/, insertion_order BIGINT GENERATED BY DEFAULT AS IDENTITY/g, '')
    .replaceAll('BYTEA', 'BLOB');
  sqlite.exec(schema);
  const salt = 'abc12345'.repeat(4);
  const hash = salt + ':' + scryptSync('existing-password-123', salt, 64).toString('hex');
  const stamp = '2026-01-01T00:00:00.000Z';
  const booking = JSON.stringify({
    id: 'booking-one',
    customer: 'Existing Customer',
    customerId: 'customer-one',
    tour: 'Existing trip',
    amount: 1000,
    paid: 200,
    travelers: 2,
    status: 'Confirmed',
    travelDate: '2099-01-01',
  });
  const records = {
    users: [
      ['customer-one', 'Existing Customer', 'existing@example.test', hash, 'customer', 1],
      ['team-one', 'Existing Team', 'team@example.test', 'disabled', 'team', 1],
      ['admin-one', 'Existing Admin', 'admin@example.test', 'disabled', 'admin', 1],
    ],
    sessions: [['hashed-session-token', 'customer-one', Date.now() + 3600000]],
    attempts: [['customer-login:existing@example.test', 2, Date.now() + 900000]],
    enquiries: [
      [
        'enquiry-one',
        'customer-one',
        'team-one',
        'Goa',
        'Existing request',
        'Quoted',
        '',
        'Existing notes',
        stamp,
      ],
    ],
    activity: [['activity-one', 'admin-one', 'Existing activity', stamp]],
    customer_profiles: [['customer-one', '1234567890', 'City', 'Address', 'Preferences', stamp]],
    admin_leads: [['lead-one', '{"id":"lead-one"}', 'existing-submission-key']],
    travel_bookings: [['booking-one', 'quote-one', booking]],
    booking_payments: [
      [
        'payment-one',
        'booking-one',
        JSON.stringify({
          id: 'payment-one',
          bookingId: 'booking-one',
          amount: 200,
          reference: 'existing-ref',
        }),
      ],
    ],
    website_booking_requests: [['existing-request-key', 'booking-one']],
    website_content: [[1, 3, '{"existing":true}', stamp]],
    website_reviews: [
      ['review-one', 'Existing Reviewer', 'Goa', 5, 'An existing published review.', 1, 1, stamp],
    ],
    travel_feature_migrations: [[1, stamp]],
    trip_plans: [['booking-one', 7, '{"name":"Coordinator"}', '[]', '[]', stamp]],
    trip_services: [
      ['service-one', 'booking-one', 'hotel', 'Confirmed', '{"name":"Hotel"}', stamp],
    ],
    trip_documents: [
      ['document-one', 'service-one', 'ticket.pdf', 'application/pdf', 8, Buffer.from('%PDF-123')],
    ],
    trip_notifications: [['notice-one', 'booking-one', 'Existing update', stamp, 0]],
  };
  for (const [table, rows] of Object.entries(records))
    for (const row of rows)
      sqlite.prepare(`INSERT INTO ${table} VALUES(${row.map(() => '?').join(',')})`).run(...row);
  assert(fs.statSync(source + '-wal').size > 0, 'Fixture must contain live WAL data.');
  const client = await connect();
  const q = (sql, values = []) =>
    client.query(
      sql.replace(
        /\b(FROM|INTO|UPDATE|TABLE) ([a-z_]+)/g,
        (_, op, table) => `${op} "${schemaName()}".${table}`,
      ),
      values,
    );
  try {
    const imported = await importSqlite(source, false, { quiet: true });
    assert.equal(imported.tables.length, 17);
    for (const result of imported.tables) {
      assert.equal(result.sourceRows, records[result.table].length);
      assert.equal(result.inserted, result.sourceRows);
      assert.equal(result.verified, result.sourceRows);
      assert.equal(
        Number((await q(`SELECT count(*) count FROM ${result.table}`)).rows[0].count),
        result.sourceRows,
      );
    }
    assert.equal(
      (await q('SELECT password FROM users WHERE id=$1', ['customer-one'])).rows[0].password,
      hash,
    );
    assert(
      (await q('SELECT content FROM trip_documents')).rows[0].content.equals(
        Buffer.from('%PDF-123'),
      ),
    );
    assert.equal((await q('SELECT revision FROM trip_plans')).rows[0].revision, 7);
    assert.equal((await q('SELECT expires FROM sessions')).rows[0].expires, records.sessions[0][2]);
    const repeat = await importSqlite(source, false, { quiet: true });
    assert(repeat.tables.every((result) => result.inserted === 0));
    assert.equal((await importSqlite(source, true, { quiet: true })).tables.length, 17);
    assert(fs.existsSync(imported.backupPath));
    assert(fs.existsSync(imported.backupPath + '.verification.json'));
    // Import would insert a new account before finding this later conflict.
    sqlite
      .prepare('INSERT INTO users VALUES(?,?,?,?,?,?)')
      .run('new-customer', 'New Customer', 'new@example.test', hash, 'customer', 1);
    await q('UPDATE website_reviews SET body=$1 WHERE id=$2', [
      'Changed in PostgreSQL',
      'review-one',
    ]);
    await assert.rejects(() => importSqlite(source, false, { quiet: true }), /conflicting/);
    assert.equal((await q('SELECT id FROM users WHERE id=$1', ['new-customer'])).rowCount, 0);
    assert.equal(
      (await q('SELECT body FROM website_reviews')).rows[0].body,
      'Changed in PostgreSQL',
    );
    sqlite.exec('CREATE TABLE unmapped_data(id TEXT)');
    await assert.rejects(
      () => importSqlite(source, false, { quiet: true }),
      /Unmapped SQLite tables/,
    );
    // Constraint and index behavior remains equivalent to SQLite.
    await assert.rejects(
      () => q('UPDATE users SET role=$1 WHERE id=$2', ['invalid', 'customer-one']),
      (error) => error.code === '23514',
    );
    await assert.rejects(
      () =>
        q('INSERT INTO travel_bookings(id,quote_id,payload) VALUES($1,$2,$3)', [
          'duplicate',
          'quote-one',
          '{}',
        ]),
      (error) => error.code === '23505',
    );
    await assert.rejects(
      () =>
        q('INSERT INTO booking_payments(id,booking_id,payload) VALUES($1,$2,$3)', [
          'orphan',
          'missing',
          '{}',
        ]),
      (error) => error.code === '23503',
    );
    await assert.rejects(
      () => q('UPDATE trip_services SET status=$1', ['invalid']),
      (error) => error.code === '23514',
    );
    await q('DELETE FROM trip_services WHERE id=$1', ['service-one']);
    assert.equal((await q('SELECT id FROM trip_documents')).rowCount, 0);
    console.log(
      'PASS: all 17 tables, WAL backup, exact hashes/blobs/sessions, row counts, repeat import, verification, conflict rollback, unknown-table rejection, constraints and cascading documents.',
    );
  } finally {
    sqlite.close();
    await client.end();
  }
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
